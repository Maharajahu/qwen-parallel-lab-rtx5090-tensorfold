import assert from 'node:assert/strict';
import * as THREE from './vendor/three.core.min.js';
import {createGeometrySDK} from './geometry_sdk.mjs';
const sdk=createGeometrySDK(THREE),material=new THREE.MeshBasicMaterial();
const roof=sdk.gable(10,20,6,material,material);
roof.updateMatrixWorld(true);
assert.deepEqual(new THREE.Box3().setFromObject(roof).getSize(new THREE.Vector3()).toArray(),[10,6,20]);
const down=new THREE.Raycaster(new THREE.Vector3(2,20,0),new THREE.Vector3(0,-1,0));
assert.ok(Math.abs(down.intersectObject(roof)[0].point.y-3.6)<1e-5,'Roof slope must face outwards');
const arch=sdk.arch(4,6,1,.4,material);arch.updateMatrixWorld(true);
assert.equal(new THREE.Raycaster(new THREE.Vector3(0,2,10),new THREE.Vector3(0,0,-1)).intersectObject(arch).length,0,'Arch must have a real opening');
assert.ok(new THREE.Raycaster(new THREE.Vector3(1.9,2,10),new THREE.Vector3(0,0,-1)).intersectObject(arch).length>0,'Arch needs solid columns');
const window=sdk.window(2,5,material,new THREE.MeshBasicMaterial({color:0xffbb44}));window.updateMatrixWorld(true);
assert.ok(new THREE.Raycaster(new THREE.Vector3(.3,1,10),new THREE.Vector3(0,0,-1)).intersectObject(window,true).length>0,'Glass must be visible from outside');
const rings=[-4,0].map(y=>Array.from({length:16},(_,i)=>[5*Math.cos(i/16*Math.PI*2),y,5*Math.sin(i/16*Math.PI*2)]));
const solid=sdk.solidRings(rings,material,material);solid.updateMatrixWorld(true);
assert.ok(new THREE.Raycaster(new THREE.Vector3(20,-2,0),new THREE.Vector3(-1,0,0)).intersectObject(solid).length>0,'Rock sides must face outward');
assert.equal(new THREE.Raycaster(new THREE.Vector3(0,10,0),new THREE.Vector3(0,-1,0)).intersectObject(solid)[0].point.y,0,'Rock top must be closed and face upward');
const reversed=sdk.solidRings([...rings].reverse(),material,material);reversed.updateMatrixWorld(true);
assert.ok(new THREE.Raycaster(new THREE.Vector3(20,-2,0),new THREE.Vector3(-1,0,0)).intersectObject(reversed).length>0,'Reversed model ring order must retain outward faces');
console.log('8 geometry assertions passed');
